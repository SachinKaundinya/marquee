export function normalizeTitleKey(title: string): string {
  if (!title) return '';
  return title
    .toLowerCase()
    .replace(/[^\w\s]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function getImdbRating(title: string, tmdbId?: number): number | undefined {
  if (tmdbId && IMDB_RATINGS_BY_ID[tmdbId] !== undefined) {
    return IMDB_RATINGS_BY_ID[tmdbId];
  }
  if (!title) return undefined;

  const exactKey = title.toLowerCase().trim();
  if (IMDB_RATINGS_MAP[exactKey] !== undefined) {
    return IMDB_RATINGS_MAP[exactKey];
  }

  const normalized = normalizeTitleKey(title);
  if (IMDB_RATINGS_MAP[normalized] !== undefined) {
    return IMDB_RATINGS_MAP[normalized];
  }

  return undefined;
}
